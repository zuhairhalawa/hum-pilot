// Writes docs/ACCURACY.md from docs/accuracy.json (and test-results/e2e-mic.json if present).
// Usage: node --experimental-strip-types scripts/report.ts
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const acc = JSON.parse(readFileSync('docs/accuracy.json', 'utf8'));
const pct = (x: number) => `${(100 * x).toFixed(1)}%`;
const c = (x: number) => `${x.toFixed(1)}`;
const conds: [string, string][] = [
  ['clean', 'Quiet room'],
  ['snr20', 'Room noise, SNR 20 dB'],
  ['snr10', 'Room noise, SNR 10 dB'],
  ['snr5', 'Room noise, SNR 5 dB (very loud)'],
];

let md = `# Accuracy report

Generated by \`npm run accuracy\` on ${acc.date} (then \`scripts/report.ts\`). Every number below
comes from synthetic hums, so the true pitch of every sample is known. No real voices were used.

**Test material.** Four synthetic voices (deep F2-F3, warm A2-A3, light F3-F4, high A#3-C5),
each humming every note of its range for 1.1 s with a breath between. A hum is modelled as a
harmonic source shaped by a nasal-murmur resonance (250-330 Hz), with ±25 cents vibrato,
slow drift (±12 cents), 0.3% period jitter, shimmer and breath noise at each onset. "Room noise"
adds pink noise at the stated signal-to-noise ratio.

**How it is measured.** The detector runs exactly as in the browser: a 2048-sample buffer at
48 kHz, 60 times a second.
- *Detector accuracy*: raw YIN output against the true pitch at the buffer centre.
- *Steering accuracy*: the smoothed pitch that moves the plane, against the note being hummed
  (no vibrato, no drift), since that is what the player means.
- *Wrong note*: more than 50 cents (half a semitone) off. *Octave error*: about 12 or 19 semitones off.
- *Heard*: share of humming frames the game treats as humming (otherwise the plane glides).
- *Latency*: from an instant note change to 3 frames in a row within 50 cents of the new note,
  on the game's frame clock (24 changes: 4 voices × steps of +2, +5, +7, −5, −12, +12 semitones).

## Pure tones (detector only)

25 sine tones from 70 to 800 Hz.

| Detector | Median error | Worst error |
| --- | --- | --- |
| Autocorrelation peak (version 0) | ${acc.sines.acf.medianCents.toFixed(2)} cents | ${acc.sines.acf.worstCents.toFixed(0)} cents |
| YIN (shipped) | ${acc.sines.yin.medianCents.toFixed(2)} cents | ${acc.sines.yin.worstCents.toFixed(1)} cents |

## Detector accuracy on hums (raw, against the true pitch)

| Condition | Detector | Median error | 95th pct | Wrong note | Octave errors |
| --- | --- | --- | --- | --- | --- |
`;
for (const [id, label] of conds) {
  for (const det of ['acf', 'yin']) {
    const s = acc.detector[det][id];
    md += `| ${label} | ${det === 'acf' ? 'Autocorrelation' : 'YIN'} | ${c(s.medianAbsCents)} c | ${c(s.p95AbsCents)} c | ${pct(s.gross)} | ${pct(s.octave)} |\n`;
  }
}

md += `
## Steering accuracy and latency, every version

Each version is one step in [TEST-LOG.md](TEST-LOG.md).

| Version | What changed | Wrong note (quiet) | Wrong note (SNR 10 dB) | Octave (SNR 10 dB) | Heard (SNR 10 dB) | Wobble (quiet) | Latency median / worst |
| --- | --- | --- | --- | --- | --- | --- | --- |
`;
for (const [id, v] of Object.entries<any>(acc.versions)) {
  md += `| ${id} | ${v.label} | ${pct(v.control.clean.gross)} | ${pct(v.control.snr10.gross)} | ${pct(v.control.snr10.octave)} | ${pct(v.control.snr10.detected)} | ${c(v.control.clean.wobbleCents)} c | ${Math.round(v.latency.medianMs)} / ${Math.round(v.latency.worstMs)} ms |\n`;
}
const last = Object.keys(acc.versions).pop()!;
const L = acc.versions[last];
md += `
"Wobble" is the spread of the steering pitch around its own average on a held note (vibrato
that leaks through). It is not an error, but it makes the plane shake.

### Shipped version (${last}) in all four conditions

| Condition | Median error | 95th pct | Wrong note | Octave errors | Heard |
| --- | --- | --- | --- | --- | --- |
`;
for (const [id, label] of conds) {
  const s = L.control[id];
  md += `| ${label} | ${c(s.medianAbsCents)} c | ${c(s.p95AbsCents)} c | ${pct(s.gross)} | ${pct(s.octave)} | ${pct(s.detected)} |\n`;
}
md += `
Room noise with nobody humming (5 s at about −40 dBFS): ${pct(acc.noiseOnly[last])} of frames heard as a hum.
YIN compute time: ${acc.computeMs.median.toFixed(2)} ms per frame median (Node, i7-13700HX), well inside the 16.7 ms frame.

## In a real browser

`;
if (existsSync('test-results/e2e-mic.json')) {
  const e = JSON.parse(readFileSync('test-results/e2e-mic.json', 'utf8'));
  md += `Microsoft Edge, started with a fake microphone that plays a synthetic hum
(\`--use-file-for-fake-audio-capture\`, files made by \`npm run fixtures\`), on ${e.base}, ${e.date.slice(0, 10)}.
Each recording does the warm-up, pauses, then hums the tune the gates spell.
Run it with \`node --experimental-strip-types scripts/e2e-mic.ts <url>\`.

| Recording | Range found | Result | Missed gates (expected) | Browser vs offline delay | Result |
| --- | --- | --- | --- | --- | --- |
`;
  for (const r of e.report) {
    if (r.matched) {
      md += `| ${r.fixture} (practice) | ${r.range.low}-${r.range.high} (MIDI) | ${r.matched} notes matched | – | – | ${r.ok ? 'pass' : 'FAIL'} |\n`;
    } else {
      md += `| ${r.fixture} | ${r.expectedRange.lowName}-${r.expectedRange.highName} | ${r.threaded} gates | ${JSON.stringify(r.missed)} (${JSON.stringify(r.expectMissed)}) | median ${r.browserMinusOfflineMs.median} ms (${r.browserMinusOfflineMs.min} to ${r.browserMinusOfflineMs.max}) | ${r.ok ? 'pass' : 'FAIL'} |\n`;
    }
  }
  md += `
"Browser vs offline delay" compares when the browser's steering pitch settled on each new
note with when the same detector, run offline on the same file, settled. Near zero means the
live audio path (microphone, AnalyserNode, animation frames) adds no measurable delay
beyond the detector itself. Edge reported an audio input latency of ${e.report[0].baseLatencyMs} ms and YIN took
${e.report[0].detectMsMedian?.toFixed(2)} ms per frame in the page.
`;
}
md += `
## Limits

- Synthetic voices only. Not yet scored on labelled recordings of real people.
- In very loud rooms (SNR 5 dB) the game hears few frames and glides; see TEST-LOG.md.
- Microphone and speaker latency of a given device is not included in the numbers above.
`;
writeFileSync('docs/ACCURACY.md', md);
console.log('wrote docs/ACCURACY.md');
